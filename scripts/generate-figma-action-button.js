/**
 * @file scripts/generate-figma-action-button.js
 * @description Code-to-Figma Component Set Template Generator (2nd revision: bug-fixed)
 *
 * Generates a self-contained Figma Plugin / Scripter script that creates a Figma
 * Component Set Node whose variant property names match the real React SEED 2.0
 * ActionButton props, with real colors/sizes applied (not just named in a comment).
 *
 * This script is the single place that owns the spec (imported from
 * ./action-button-spec.js) and templates it into the generated plugin file, so the
 * two files can no longer drift out of sync the way they did before this refactor.
 *
 * Fixes applied vs. the previous version:
 * - styleMapping is now actually applied to component fills/strokes/text color
 *   (previously defined but never used, so every variant rendered identically).
 * - size values corrected to match @seed-design/css/recipes/action-button.css
 *   exactly (medium was 44 -> 40, xsmall was 28 -> 32).
 * - cornerRadius is now per-size (was hardcoded to 8 for every size; xsmall is
 *   actually a full pill and large is 12).
 * - variant list corrected to the real 7 SEED variants (removed the invented
 *   "criticalWeak", added the missing "brandOutline" and "ghost").
 * - the generated script now looks up the running file's local Figma Variables
 *   by name first, and only falls back to the literal hex in the spec if no
 *   matching variable exists — so it works both in a file with SEED tokens
 *   already bound (Author's) and in a fresh file (fallback).
 * - disabled variants now actually render in the disabled bg/fg colors instead
 *   of just being labeled "disabled=true" with the enabled variant's colors.
 */

const fs = require("fs");
const path = require("path");
const { ACTION_BUTTON_SPEC } = require("./action-button-spec");

function generateFigmaPluginCode(spec) {
  return `// ============================================================================
// Figma Plugin / Scripter Code: Auto-Generate ActionButton ComponentSet
// AxKit SEED 2.0 Code-to-Figma Template Generator (2nd revision, bug-fixed)
//
// Generated by scripts/generate-figma-action-button.js — do not hand-edit this
// file. Edit scripts/action-button-spec.js and re-run the generator instead.
// ============================================================================

(async function createActionButtonComponentSet() {
  await figma.loadFontAsync({ family: "Inter", style: "Bold" });

  const spec = ${JSON.stringify(spec, null, 2)};

  // Best-effort local Variable lookup: prefer the running file's own bound
  // tokens (names vary per project), fall back to the spec's literal hex.
  const collections = await figma.variables.getLocalVariableCollectionsAsync();
  const varsByName = {};
  for (const collection of collections) {
    const vars = await Promise.all(
      collection.variableIds.map((id) => figma.variables.getVariableByIdAsync(id)),
    );
    for (const v of vars) varsByName[v.name] = v;
  }

  function resolveVariable(candidateNames) {
    if (!candidateNames) return null;
    for (const name of candidateNames) {
      if (varsByName[name]) return varsByName[name];
    }
    return null;
  }

  function hexToRgb(hex) {
    return {
      r: parseInt(hex.slice(1, 3), 16) / 255,
      g: parseInt(hex.slice(3, 5), 16) / 255,
      b: parseInt(hex.slice(5, 7), 16) / 255,
    };
  }

  // Binds a Figma Variable to a paint if one was found in this file, otherwise
  // falls back to the literal resolved hex from the spec.
  function makeFill(hex, candidateVarNames) {
    const variable = resolveVariable(candidateVarNames);
    let paint = { type: "SOLID", color: hexToRgb(hex) };
    if (variable) paint = figma.variables.setBoundVariableForPaint(paint, "color", variable);
    return paint;
  }

  const components = [];

  let xOffset = 0;
  let yOffset = 0;
  const GAP_X = 160;
  const GAP_Y = 80;
  let colCount = 0;

  for (const variant of spec.properties.variant) {
    for (const size of spec.properties.size) {
      for (const disabledFlag of spec.properties.disabled) {
        for (const loadingFlag of spec.properties.loading) {
          const isDisabled = disabledFlag === "true";
          const isLoading = loadingFlag === "true";

          const sizeMeta = spec.sizeMapping[size];
          const style = spec.styleMapping[variant];
          // Disabled overrides bg/fg regardless of variant, matching the real
          // ":is(:disabled, [disabled], [data-disabled])" CSS rule.
          const bgHex = isDisabled ? spec.disabledOverride.bg : style.bg;
          const bgVarNames = isDisabled ? spec.disabledOverride.bgVar : style.bgVar;
          const fgHex = isDisabled ? spec.disabledOverride.fg : style.fg;
          const fgVarNames = isDisabled ? spec.disabledOverride.fgVar : style.fgVar;

          // Create Component Frame
          const comp = figma.createComponent();
          comp.name = \`variant=\${variant}, size=\${size}, disabled=\${disabledFlag}, loading=\${loadingFlag}\`;

          // Layout & Sizing
          comp.layoutMode = "HORIZONTAL";
          comp.primaryAxisAlignItems = "CENTER";
          comp.counterAxisAlignItems = "CENTER";
          comp.paddingLeft = sizeMeta.paddingX;
          comp.paddingRight = sizeMeta.paddingX;
          comp.resize(comp.width, sizeMeta.height);
          comp.primaryAxisSizingMode = "AUTO";
          comp.counterAxisSizingMode = "FIXED";
          comp.cornerRadius = sizeMeta.radius;

          // Fill: solid variants get a real background; outline/ghost stay transparent.
          if (bgHex) {
            comp.fills = [makeFill(bgHex, bgVarNames)];
          } else {
            comp.fills = [];
          }

          // Border: only brandOutline / neutralOutline define one.
          if (style.border && !isDisabled) {
            comp.strokes = [makeFill(style.border, style.borderVar)];
            comp.strokeWeight = 1;
          } else if (style.border && isDisabled) {
            // Real recipe keeps the neutral-muted border on disabled outline variants.
            comp.strokes = [makeFill(style.border, style.borderVar)];
            comp.strokeWeight = 1;
          } else {
            comp.strokes = [];
          }

          // Text Node
          const textNode = figma.createText();
          textNode.fontName = { family: "Inter", style: "Bold" };
          textNode.characters = isLoading ? "로딩 중..." : "버튼 라벨";
          textNode.fontSize = sizeMeta.fontSize;
          textNode.fills = [makeFill(fgHex, fgVarNames)];

          comp.appendChild(textNode);

          // Position in grid
          comp.x = xOffset;
          comp.y = yOffset;

          colCount++;
          xOffset += GAP_X;
          if (colCount % 8 === 0) {
            xOffset = 0;
            yOffset += GAP_Y;
          }

          components.push(comp);
        }
      }
    }
  }

  // Combine into ComponentSetNode
  const componentSet = figma.combineAsVariants(components, figma.currentPage);
  componentSet.name = spec.name;

  figma.viewport.scrollAndZoomIntoView([componentSet]);
  figma.notify(
    \`✅ ActionButton ComponentSet 템플릿(\${components.length}개 Variant)이 성공적으로 피그마에 생성되었습니다!\`,
  );
})();
`;
}

const pluginCode = generateFigmaPluginCode(ACTION_BUTTON_SPEC);
const outputPath = path.join(__dirname, "figma-action-button-plugin.js");

fs.writeFileSync(outputPath, pluginCode, "utf-8");
console.log(`[Success] ActionButton Figma Plugin Code generated at: ${outputPath}`);
